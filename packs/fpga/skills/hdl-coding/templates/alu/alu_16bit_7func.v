// template: alu_16bit_7func
// version: 1.1.0
// domain: alu
// description: 16 位 7 功能 ALU — 外部资料改编
// requires: 无
//-----------------------------------------------------------------
//                    16位7功能算术逻辑部件
//-----------------------------------------------------------------
// 名称: alu_16bit_7func
// 功能描述: 实现16位7功能ALU
// 应用场景: 通用算术逻辑运算
// 主要逻辑: 功能码 i_fc 选出进位生成/传输函数 (w_g/w_p), 四组
//           carry_lookahead_4bit 分段求进位 + 一组组间超前进位链 (u_clx),
//           再拼出 17 位进位向量 w_c, 由其生成结果与四个标志位
// 功能列表:
//   000: A + B
//   001: A - B
//   010: A + B + Ci
//   011: A - B - Ci
//   100: A & B
//   101: A | B
//   110: A ^ B
//   111: A ^ B
//
// 红线 1/2 适用性说明:
//   本模块是**无时钟纯组合原语**, 没有时钟域也就没有可寄存的对象, 红线 1/2
//   在此不可实施 —— 给 ALU 加流水级会改变它的契约 (同拍出结果是 ALU 的定义)。
//   **调用方责任**: 例化方必须自己完成寄存 —— i_* 由上级 ri_* 驱动, o_* 被上级
//   ro_* 采样。红线 1/2 由该寄存边界承担, 不是被豁免。
//   注: 16 位全展开超前进位链组合深度较大, 若上级时钟较高, 应在 i_/o_ 两侧
//   各加一级寄存, 或改用分段流水加法器。
//-----------------------------------------------------------------
// 输入:
//   i_a     - 操作数A（16位）
//   i_b     - 操作数B（16位）
//   i_ci    - 进位输入
//   i_fc    - 功能控制（3位）
// 输出:
//   o_d     - 结果输出（16位）
//   o_cf    - 进位标志
//   o_zf    - 零标志
//   o_sf    - 符号标志
//   o_of    - 溢出标志
//-----------------------------------------------------------------

module alu_16bit_7func (
    input  wire [15:0] i_a,
    input  wire [15:0] i_b,
    input  wire        i_ci,
    input  wire [2:0]  i_fc,
    output wire [15:0] o_d,
    output wire        o_cf,
    output wire        o_zf,
    output wire        o_sf,
    output wire        o_of
);

    //-----------------------------------------------------------------
    // 内部信号定义
    // w_ 前缀: 组合语义 (always @(*) 驱动的 reg 是组合网络, 非触发器)
    //-----------------------------------------------------------------
    reg  [15:0] w_g, w_p;
    wire [16:0] w_c;
    wire [3:0]  w_gl, w_pl;
    wire [4:1]  w_cx;
    wire [16:1] w_ct;

    //-----------------------------------------------------------------
    // 进位生成函数G
    //-----------------------------------------------------------------
    always @(*) begin
        case (i_fc)
            3'b000: w_g = i_a & i_b;
            3'b001: w_g = i_a & (~i_b);
            3'b010: w_g = i_a & i_b;
            3'b011: w_g = i_a & (~i_b);
            3'b100: w_g = i_a & i_b;
            3'b101: w_g = {16{1'b0}};
            3'b110: w_g = i_a & i_b;
            3'b111: w_g = i_a & i_b;
            default: w_g = i_a & i_b;
        endcase
    end

    //-----------------------------------------------------------------
    // 进位传输函数P
    //-----------------------------------------------------------------
    always @(*) begin
        case (i_fc)
            3'b000: w_p = i_a | i_b;
            3'b001: w_p = i_a | (~i_b);
            3'b010: w_p = i_a | i_b;
            3'b011: w_p = i_a | (~i_b);
            3'b100: w_p = {16{1'b0}};
            3'b101: w_p = i_a | i_b;
            3'b110: w_p = i_a | i_b;
            3'b111: w_p = i_a | i_b;
            default: w_p = i_a | i_b;
        endcase
    end

    //-----------------------------------------------------------------
    // 进位链输入
    //-----------------------------------------------------------------
    wire w_cp;
    assign w_cp = ((i_ci & i_fc[1]) ^ i_fc[0]);

    //-----------------------------------------------------------------
    // 4位超前进位链实例化 (具名端口连接)
    //-----------------------------------------------------------------
    carry_lookahead_4bit u_cl0 (
        .i_g (w_g[3:0]),   .i_p (w_p[3:0]),   .i_ci (w_cp),
        .o_c (w_ct[4:1]),  .o_gl (w_gl[0]),   .o_pl (w_pl[0])
    );
    carry_lookahead_4bit u_cl1 (
        .i_g (w_g[7:4]),   .i_p (w_p[7:4]),   .i_ci (w_cx[1]),
        .o_c (w_ct[8:5]),  .o_gl (w_gl[1]),   .o_pl (w_pl[1])
    );
    carry_lookahead_4bit u_cl2 (
        .i_g (w_g[11:8]),  .i_p (w_p[11:8]),  .i_ci (w_cx[2]),
        .o_c (w_ct[12:9]), .o_gl (w_gl[2]),   .o_pl (w_pl[2])
    );
    carry_lookahead_4bit u_cl3 (
        .i_g (w_g[15:12]), .i_p (w_p[15:12]), .i_ci (w_cx[3]),
        .o_c (w_ct[16:13]),.o_gl (w_gl[3]),   .o_pl (w_pl[3])
    );
    carry_lookahead_4bit u_clx (
        .i_g (w_gl[3:0]),  .i_p (w_pl[3:0]),  .i_ci (w_cp),
        .o_c (w_cx[4:1]),  .o_gl (),          .o_pl ()
    );

    //-----------------------------------------------------------------
    // 进位输出拼接
    //-----------------------------------------------------------------
    assign w_c = {w_cx[4], w_ct[15:13], w_cx[3], w_ct[11:9],
                  w_cx[2], w_ct[7:5],   w_cx[1], w_ct[3:1], w_cp};

    //-----------------------------------------------------------------
    // 结果和标志位生成
    //-----------------------------------------------------------------
    assign o_d  = w_g ^ w_p ^ ((~i_fc[2]) ? w_c[15:0] : {16{1'b0}});
    assign o_cf = (w_c[16] ^ i_fc[0]) & (~i_fc[2]);
    assign o_zf = !o_d;
    assign o_sf = w_g[15] ^ w_p[15] ^ ((~i_fc[2]) & w_c[16]);
    assign o_of = (w_c[15] ^ w_c[16]) & (~i_fc[2]);

endmodule
