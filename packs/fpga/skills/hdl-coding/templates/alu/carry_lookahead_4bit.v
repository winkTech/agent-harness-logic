//-----------------------------------------------------------------
//                    4位超前进位链模块
//-----------------------------------------------------------------
// 名称: carry_lookahead_4bit
// 功能描述: 实现4位超前进位链
// 应用场景: 高速加法器的核心组件
// 算法原理: 进位生成函数G和进位传输函数P
//
// 红线 1/2 适用性说明:
//   本模块是**无时钟纯组合原语**, 不存在时钟域, 因而没有可寄存的对象 ——
//   红线 1 (输入寄存 ri_) 与红线 2 (输出寄存 ro_) 在此不可实施: 强行加时钟和
//   流水级会改变模块契约 (从组合进位链变成带延迟的时序块), 而超前进位链的
//   全部价值就在于同拍出进位。
//   **调用方责任**: 例化本模块的上级必须自己完成输入/输出寄存 —— 即本模块的
//   i_* 应由上级的 ri_* 驱动, o_* 应被上级的 ro_* 采样, 不得让 o_* 跨模块直连
//   到再下一级的组合逻辑。红线 1/2 由该寄存边界承担, 不是被豁免。
//-----------------------------------------------------------------
// 输入:
//   i_g     - 进位生成函数（4位）
//   i_p     - 进位传输函数（4位）
//   i_ci    - 进位输入
// 输出:
//   o_c     - 进位输出（4位）
//   o_gl    - 组进位生成函数
//   o_pl    - 组进位传输函数
//-----------------------------------------------------------------

module carry_lookahead_4bit (
    input  wire [3:0] i_g,
    input  wire [3:0] i_p,
    input  wire       i_ci,
    output wire [4:1] o_c,
    output wire       o_gl,
    output wire       o_pl
);

    //-----------------------------------------------------------------
    // 超前进位链逻辑
    //-----------------------------------------------------------------
    assign o_c[1] = i_g[0] | i_p[0] & i_ci;
    assign o_c[2] = i_g[1] | i_p[1] & i_g[0] | i_p[1] & i_p[0] & i_ci;
    assign o_c[3] = i_g[2] | i_p[2] & i_g[1] | i_p[2] & i_p[1] & i_g[0] |
                    i_p[2] & i_p[1] & i_p[0] & i_ci;
    assign o_c[4] = o_gl | o_pl & i_ci;

    //-----------------------------------------------------------------
    // 组进位生成和传输函数
    //-----------------------------------------------------------------
    assign o_gl = i_g[3] | i_p[3] & i_g[2] | i_p[3] & i_p[2] & i_g[1] |
                  i_p[3] & i_p[2] & i_p[1] & i_g[0];
    assign o_pl = i_p[3] & i_p[2] & i_p[1] & i_p[0];

endmodule
