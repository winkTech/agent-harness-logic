// template: alu_4bit_16func
// version: 1.1.0
// domain: alu
// description: 4 位 16 功能 ALU — 外部资料改编
// requires: 无
//-----------------------------------------------------------------
//                    4位16功能算术逻辑部件
//-----------------------------------------------------------------
// 名称: alu_4bit_16func
// 功能描述: 实现4位16功能ALU
// 应用场景: 通用算术逻辑运算
// 主要逻辑: 功能码 i_fc 选出进位生成/传输函数 (w_g/w_p) 与进位输入 w_c0,
//           经 carry_lookahead_4bit 超前进位链求进位, 再拼出结果与四个标志位
// 功能列表:
//   0000: B
//   0001: B + 1
//   0010: A + B + Ci
//   0011: A + B
//   0100: ~B
//   0101: -B
//   0110: A - B + Ci - 1
//   0111: A - B
//   1000: B - 1
//   1001: B - A
//   1010: B - A + Ci - 1
//   1011: ~A
//   1100: A & B
//   1101: A | B
//   1110: A ^ B
//   1111: abs A
//
// 红线 1/2 适用性说明:
//   本模块是**无时钟纯组合原语**, 没有时钟域也就没有可寄存的对象, 红线 1/2
//   在此不可实施 —— 给 ALU 加流水级会改变它的契约 (同拍出结果是 ALU 的定义)。
//   **调用方责任**: 例化方必须自己完成寄存 —— i_* 由上级 ri_* 驱动, o_* 被上级
//   ro_* 采样。红线 1/2 由该寄存边界承担, 不是被豁免。
//-----------------------------------------------------------------
// 输入:
//   i_a     - 操作数A（4位）
//   i_b     - 操作数B（4位）
//   i_ci    - 进位输入
//   i_fc    - 功能控制（4位）
// 输出:
//   o_d     - 结果输出（4位）
//   o_cf    - 进位标志
//   o_zf    - 零标志
//   o_sf    - 符号标志
//   o_of    - 溢出标志
//-----------------------------------------------------------------

module alu_4bit_16func (
    input  wire [3:0] i_a,
    input  wire [3:0] i_b,
    input  wire       i_ci,
    input  wire [3:0] i_fc,
    output wire [3:0] o_d,
    output wire       o_cf,
    output wire       o_zf,
    output wire       o_sf,
    output wire       o_of
);

    //-----------------------------------------------------------------
    // 内部信号定义
    // w_ 前缀: 组合语义 (always @(*) 驱动的 reg 是组合网络, 非触发器)
    //-----------------------------------------------------------------
    reg [3:0]  w_g, w_p;
    reg        w_c0;                     // 进位输入（功能码选择，always 驱动）
    wire [4:1] w_c_chain;                // 超前进位链输出（例化端口驱动）
    wire [4:0] w_c = {w_c_chain, w_c0};  // 合成只读进位向量，避免 reg 被端口多驱动
    wire       w_ol;  // 逻辑操作标志
    wire       w_so;  // 减法操作标志

    //-----------------------------------------------------------------
    // 进位生成函数G
    //-----------------------------------------------------------------
    always @(*) begin
        case (i_fc)
            4'b0000: w_g = 4'b0000;
            4'b0001: w_g = 4'b0000;
            4'b0010: w_g = i_a & i_b;
            4'b0011: w_g = i_a & i_b;
            4'b0100: w_g = 4'b0000;
            4'b0101: w_g = 4'b0000;
            4'b0110: w_g = i_a & (~i_b);
            4'b0111: w_g = i_a & (~i_b);
            4'b1000: w_g = i_b;
            4'b1001: w_g = (~i_a) & i_b;
            4'b1010: w_g = (~i_a) & i_b;
            4'b1011: w_g = 4'b0000;
            4'b1100: w_g = i_a & i_b;
            4'b1101: w_g = 4'b0000;
            4'b1110: w_g = i_a & i_b;
            4'b1111: w_g = 4'b0000;
            default: w_g = 4'b0000;
        endcase
    end

    //-----------------------------------------------------------------
    // 进位传输函数P
    //-----------------------------------------------------------------
    always @(*) begin
        case (i_fc)
            4'b0000: w_p = i_b;
            4'b0001: w_p = i_b;
            4'b0010: w_p = i_a | i_b;
            4'b0011: w_p = i_a | i_b;
            4'b0100: w_p = (~i_b);
            4'b0101: w_p = (~i_b);
            4'b0110: w_p = i_a | (~i_b);
            4'b0111: w_p = i_a | (~i_b);
            4'b1000: w_p = 4'b1111;
            4'b1001: w_p = (~i_a) | i_b;
            4'b1010: w_p = (~i_a) | i_b;
            4'b1011: w_p = (~i_a);
            4'b1100: w_p = 4'b0000;
            4'b1101: w_p = i_a | i_b;
            4'b1110: w_p = i_a | i_b;
            4'b1111: w_p = (i_a[3] ? (~i_a) : i_a);
            default: w_p = i_a | i_b;
        endcase
    end

    //-----------------------------------------------------------------
    // 进位输入C[0]
    // 逻辑操作 (1100/1101/1110) 不使用进位链, w_c0 取 0 即可 —— 原资料此处
    // 写 1'bx, 综合器可自由取值, 会让仿真与上板出现不同的 w_c 向量; 本模板
    // 统一取确定值 0, 消除该仿真-综合差异 (逻辑操作下 w_ol=1 已屏蔽进位)
    //-----------------------------------------------------------------
    always @(*) begin
        case (i_fc)
            4'b0000: w_c0 = 1'b0;
            4'b0001: w_c0 = 1'b1;
            4'b0010: w_c0 = i_ci;
            4'b0011: w_c0 = 1'b0;
            4'b0100: w_c0 = 1'b0;
            4'b0101: w_c0 = 1'b1;
            4'b0110: w_c0 = i_ci;
            4'b0111: w_c0 = 1'b1;
            4'b1000: w_c0 = 1'b0;
            4'b1001: w_c0 = 1'b1;
            4'b1010: w_c0 = i_ci;
            4'b1011: w_c0 = 1'b0;
            4'b1100: w_c0 = 1'b0;
            4'b1101: w_c0 = 1'b0;
            4'b1110: w_c0 = 1'b0;
            4'b1111: w_c0 = i_a[3];
            default: w_c0 = 1'b0;
        endcase
    end

    //-----------------------------------------------------------------
    // 逻辑操作和减法操作标志
    //-----------------------------------------------------------------
    assign w_ol = (i_fc == 4'b1100) | (i_fc == 4'b1101) | (i_fc == 4'b1110);
    assign w_so = (i_fc == 4'b0101) | (i_fc == 4'b0110) | (i_fc == 4'b0111) |
                  (i_fc == 4'b1000) | (i_fc == 4'b1001) | (i_fc == 4'b1010) |
                  ((i_fc == 4'b1111) & i_a[3]);

    //-----------------------------------------------------------------
    // 4位超前进位链实例化 (具名端口连接)
    //-----------------------------------------------------------------
    carry_lookahead_4bit u_cl4 (
        .i_g  (w_g),
        .i_p  (w_p),
        .i_ci (w_c0),
        .o_c  (w_c_chain),
        .o_gl (),
        .o_pl ()
    );

    //-----------------------------------------------------------------
    // 结果和标志位生成
    //-----------------------------------------------------------------
    assign o_d  = w_g ^ w_p ^ ((~w_ol) ? w_c[3:0] : 4'b0000);
    assign o_cf = (w_c[4] ^ w_so) & (~w_ol);
    assign o_zf = !o_d;
    // 已知缺陷 (承自外部资料, 本次规范修复未改其逻辑):
    //   o_sf 未像 o_cf/o_of 那样用 (~w_ol) 屏蔽进位链, 逻辑操作 (1100/1101/1110)
    //   下 o_sf 不等于结果符号位 o_d[3]。对照 alu_16bit_7func 的写法应为
    //   `w_g[3] ^ w_p[3] ^ ((~w_ol) & w_c[4])`。这是功能缺陷而非编码规范问题,
    //   修改会改变模块行为契约, 故此处只标注不擅改 —— 复用本模板前请先决策。
    assign o_sf = w_g[3] ^ w_p[3] ^ w_c[4];
    assign o_of = (w_c[4] ^ w_c[3]) & (~w_ol);

endmodule
