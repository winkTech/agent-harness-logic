function [pass, detail] = test_encode_decode()
% 测试1: 编码译码一致性 (无噪声)
% 验证: info == dec(enc(info), H) 无噪声下完全一致

    cfg = config_test();
    H = generate_h_matrix(cfg);

    num_tests = 10;
    for t = 1:num_tests
        info = randi([0 1], cfg.K, 1);
        code = ldpc_encode_80211n(info, H, cfg);

        % 校验 H·code = 0
        parity = mod(full(H) * double(code), 2);
        assert(all(parity == 0), '测试 %d: 编码校验失败', t);

        % 无噪声译码
        tx = 1 - 2 * double(code);
        llr = 20 * tx;

        [dec_info, iter] = ldpc_decoder_ms_pure(llr, H, cfg.max_iter, cfg.scale_factor);

        assert(isequal(dec_info, info), ...
            '测试 %d: 译码错误 (iter=%d)', t, iter);
    end

    pass = true;
    detail = sprintf('%d/10 通过', num_tests);
end

