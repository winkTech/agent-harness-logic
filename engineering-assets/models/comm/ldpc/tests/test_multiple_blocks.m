function [pass, detail] = test_multiple_blocks()
% 测试5: 多码块连续处理 — 编码器/译码器状态复位验证
% 连续编码译码 20 个码块，每块独立校验

    cfg = config_test();
    H = generate_h_matrix(cfg);

    num_blocks = 20;
    failures = 0;

    for blk = 1:num_blocks
        info = randi([0 1], cfg.K, 1);
        code = ldpc_encode_80211n(info, H, cfg);

        % 校验 H·code = 0
        assert(all(mod(double(full(H)) * double(code), 2) == 0), ...
            '块 %d: 编码校验失败', blk);

        % 无噪声译码
        llr = 20 * (1 - 2 * double(code));
        [dec_info, ~] = ldpc_decoder_ms_pure(llr, H, 20, cfg.scale_factor);

        if ~isequal(dec_info(1:length(info)), info)
            failures = failures + 1;
        end
    end

    assert(failures == 0, '%d/%d 块译码失败', failures, num_blocks);

    pass = true;
    detail = sprintf('%d/%d 块全部正确', num_blocks, num_blocks);
end

