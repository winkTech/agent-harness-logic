//-----------------------------------------------------------------
//                         Crossbar交叉点单元
//-----------------------------------------------------------------
// 功能描述: Crossbar交换矩阵基本单元
// 应用场景: 网络交换机、路由器、数据交换单元
// 特点: N×N无阻塞交换，高带宽、低延迟
//-----------------------------------------------------------------
// 输入:
//   i_clk_sys      - 系统时钟
//   i_rst_sys      - 系统复位（高有效）
//   i_wr_en        - 写使能
//   i_wr_data      - 写入数据
//   i_sel          - 选择信号
// 输出:
//   o_rd_data      - 读出数据
//-----------------------------------------------------------------

module crossbar_cell (
    input  wire        i_clk_sys,
    input  wire        i_rst_sys,
    input  wire        i_wr_en,
    input  wire [7:0]  i_wr_data,
    input  wire        i_sel,
    output wire [7:0]  o_rd_data
);

    //-----------------------------------------------------------------
    // 交叉点寄存器
    //-----------------------------------------------------------------
    reg [7:0] r_data;

    //-----------------------------------------------------------------
    // 写操作
    //-----------------------------------------------------------------
    always @(posedge i_clk_sys) begin
        if (i_rst_sys) begin
            r_data <= 0;
        end else if (i_wr_en && i_sel) begin
            r_data <= i_wr_data;
        end
    end

    //-----------------------------------------------------------------
    // 读操作
    //-----------------------------------------------------------------
    assign o_rd_data = i_sel ? r_data : 8'h00;

endmodule
