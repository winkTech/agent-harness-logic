//-----------------------------------------------------------------
//                         CAM基本单元模块
//-----------------------------------------------------------------
// 功能描述: 内容可寻址存储器（CAM）基本单元
// 应用场景: 以太网MAC地址查找、路由表查找
// 特点: 并行查找，根据数据内容查找地址
//-----------------------------------------------------------------
// 输入:
//   i_clk_sys      - 系统时钟
//   i_wr_en        - 写使能
//   i_wr_data      - 写入数据
//   i_search_data  - 查找数据
// 输出:
//   o_match        - 匹配标志
//-----------------------------------------------------------------

module cam_cell (
    input  wire        i_clk_sys,
    input  wire        i_wr_en,
    input  wire [7:0]  i_wr_data,
    input  wire [7:0]  i_search_data,
    output reg         o_match
);

    //-----------------------------------------------------------------
    // 存储单元
    //-----------------------------------------------------------------
    reg [7:0] r_data;

    //-----------------------------------------------------------------
    // 写操作
    //-----------------------------------------------------------------
    always @(posedge i_clk_sys) begin
        if (i_wr_en) begin
            r_data <= i_wr_data;
        end
    end

    //-----------------------------------------------------------------
    // 比较操作
    //-----------------------------------------------------------------
    always @(*) begin
        o_match = (r_data == i_search_data);
    end

endmodule
