//-----------------------------------------------------------------
//                         CRC-32校验模块
//-----------------------------------------------------------------
// 功能描述: 实现CRC-32校验算法
// 应用场景: 以太网帧校验、数据完整性验证
// 算法原理: CRC-32 = x^32 + x^26 + x^23 + x^22 + x^16 + x^12 + x^11 + x^10 + x^8 + x^7 + x^5 + x^4 + x^2 + x + 1
//-----------------------------------------------------------------
// 输入:
//   i_clk_sys      - 系统时钟
//   i_rst_sys      - 系统复位（高有效）
//   i_data_valid   - 输入数据有效
//   i_data         - 输入数据（8位）
// 输出:
//   o_crc          - CRC校验结果（32位）
//-----------------------------------------------------------------

module crc32_calc (
    input  wire        i_clk_sys,
    input  wire        i_rst_sys,
    input  wire        i_data_valid,
    input  wire [7:0]  i_data,
    output reg  [31:0] o_crc
);

    //-----------------------------------------------------------------
    // 参数定义
    //-----------------------------------------------------------------
    localparam P_CRC_POLY = 32'h04C11DB7;  // CRC-32多项式

    //-----------------------------------------------------------------
    // CRC计算
    //-----------------------------------------------------------------
    always @(posedge i_clk_sys) begin
        if (i_rst_sys) begin
            o_crc <= 32'hFFFFFFFF;
        end else if (i_data_valid) begin
            o_crc <= next_crc32(o_crc, i_data);
        end
    end

    //-----------------------------------------------------------------
    // CRC下一步计算函数
    //-----------------------------------------------------------------
    function [31:0] next_crc32;
        input [31:0] crc;
        input [7:0] data;
        integer i;
        reg [31:0] c;
        reg [7:0] d;
        begin
            c = crc;
            d = data;
            for (i = 0; i < 8; i = i + 1) begin
                if ((c[31] ^ d[0]) == 1'b1) begin
                    c = (c << 1) ^ P_CRC_POLY;
                end else begin
                    c = c << 1;
                end
                d = d >> 1;
            end
            next_crc32 = c;
        end
    endfunction

endmodule
