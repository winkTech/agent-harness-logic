//                    4位超前进位链模块
//-----------------------------------------------------------------
// 功能描述: 实现4位超前进位链
// 应用场景: 高速加法器的核心组件
// 算法原理: 进位生成函数G和进位传输函数P
//-----------------------------------------------------------------
// 输入:
//   G       - 进位生成函数（4位）
//   P       - 进位传输函数（4位）
//   Ci      - 进位输入
// 输出:
//   C       - 进位输出（4位）
//   Gl      - 组进位生成函数
//   Pl      - 组进位传输函数
//-----------------------------------------------------------------

module carry_lookahead_4bit (
    input  wire [3:0] G,
    input  wire [3:0] P,
    input  wire       Ci,
    output wire [4:1] C,
    output wire       Gl,
    output wire       Pl
);

    //-----------------------------------------------------------------
    // 超前进位链逻辑
    //-----------------------------------------------------------------
    assign C[1] = G[0] | P[0] & Ci;
    assign C[2] = G[1] | P[1] & G[0] | P[1] & P[0] & Ci;
    assign C[3] = G[2] | P[2] & G[1] | P[2] & P[1] & G[0] | P[2] & P[1] & P[0] & Ci;
    assign C[4] = Gl | Pl & Ci;

    //-----------------------------------------------------------------
    // 组进位生成和传输函数
    //-----------------------------------------------------------------
    assign Gl = G[3] | P[3] & G[2] | P[3] & P[2] & G[1] | P[3] & P[2] & P[1] & G[0];
    assign Pl = P[3] & P[2] & P[1] & P[0];

endmodule
