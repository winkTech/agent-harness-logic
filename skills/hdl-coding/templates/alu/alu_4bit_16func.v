//-----------------------------------------------------------------
//                    4位16功能算术逻辑部件
//-----------------------------------------------------------------
// 功能描述: 实现4位16功能ALU
// 应用场景: 通用算术逻辑运算
// 功能列表:
//   0000: B
//   0001: B + 1
//   0010: A + B + Ci
//   0011: A + B
//   0100: ~B
//   0101: -B
//   0110: A - B + Ci - 1
//   0111: A - B
//   1000: B - 1
//   1001: B - A
//   1010: B - A + Ci - 1
//   1011: ~A
//   1100: A & B
//   1101: A | B
//   1110: A ^ B
//   1111: abs A
//-----------------------------------------------------------------
// 输入:
//   A       - 操作数A（4位）
//   B       - 操作数B（4位）
//   Ci      - 进位输入
//   Fc      - 功能控制（4位）
// 输出:
//   D       - 结果输出（4位）
//   cf      - 进位标志
//   zf      - 零标志
//   sf      - 符号标志
//   of      - 溢出标志
//-----------------------------------------------------------------

module alu_4bit_16func (
    input  wire [3:0] A,
    input  wire [3:0] B,
    input  wire       Ci,
    input  wire [3:0] Fc,
    output wire [3:0] D,
    output wire       cf,
    output wire       zf,
    output wire       sf,
    output wire       of
);

    //-----------------------------------------------------------------
    // 内部信号定义
    //-----------------------------------------------------------------
    reg [3:0] G, P;
    reg [4:0] C;
    wire ol;  // 逻辑操作标志
    wire so;  // 减法操作标志

    //-----------------------------------------------------------------
    // 进位生成函数G
    //-----------------------------------------------------------------
    always @(*) begin
        case (Fc)
            4'b0000: G = 4'b0000;
            4'b0001: G = 4'b0000;
            4'b0010: G = A & B;
            4'b0011: G = A & B;
            4'b0100: G = 4'b0000;
            4'b0101: G = 4'b0000;
            4'b0110: G = A & (~B);
            4'b0111: G = A & (~B);
            4'b1000: G = B;
            4'b1001: G = (~A) & B;
            4'b1010: G = (~A) & B;
            4'b1011: G = 0;
            4'b1100: G = A & B;
            4'b1101: G = 4'b0000;
            4'b1110: G = A & B;
            4'b1111: G = 4'b0000;
            default: G = 4'bxxxx;
        endcase
    end

    //-----------------------------------------------------------------
    // 进位传输函数P
    //-----------------------------------------------------------------
    always @(*) begin
        case (Fc)
            4'b0000: P = B;
            4'b0001: P = B;
            4'b0010: P = A | B;
            4'b0011: P = A | B;
            4'b0100: P = (~B);
            4'b0101: P = (~B);
            4'b0110: P = A | (~B);
            4'b0111: P = A | (~B);
            4'b1000: P = 4'b1111;
            4'b1001: P = (~A) | B;
            4'b1010: P = (~A) | B;
            4'b1011: P = (~A);
            4'b1100: P = 4'b0000;
            4'b1101: P = A | B;
            4'b1110: P = A | B;
            4'b1111: P = (A[3] ? (~A) : A);
            default: P = 4'bxxxx;
        endcase
    end

    //-----------------------------------------------------------------
    // 进位输入C[0]
    //-----------------------------------------------------------------
    always @(*) begin
        case (Fc)
            4'b0000: C[0] = 1'b0;
            4'b0001: C[0] = 1'b1;
            4'b0010: C[0] = Ci;
            4'b0011: C[0] = 1'b0;
            4'b0100: C[0] = 1'b0;
            4'b0101: C[0] = 1'b1;
            4'b0110: C[0] = Ci;
            4'b0111: C[0] = 1'b1;
            4'b1000: C[0] = 1'b0;
            4'b1001: C[0] = 1'b1;
            4'b1010: C[0] = Ci;
            4'b1011: C[0] = 1'b0;
            4'b1100: C[0] = 1'bx;
            4'b1101: C[0] = 1'bx;
            4'b1110: C[0] = 1'bx;
            4'b1111: C[0] = A[3];
            default: C[0] = 1'bx;
        endcase
    end

    //-----------------------------------------------------------------
    // 逻辑操作和减法操作标志
    //-----------------------------------------------------------------
    assign ol = (Fc == 4'b1100) | (Fc == 4'b1101) | (Fc == 4'b1110);
    assign so = (Fc == 4'b0101) | (Fc == 4'b0110) | (Fc == 4'b0111) |
                (Fc == 4'b1000) | (Fc == 4'b1001) | (Fc == 4'b1010) |
                ((Fc == 4'b1111) & A[3]);

    //-----------------------------------------------------------------
    // 4位超前进位链实例化
    //-----------------------------------------------------------------
    carry_lookahead_4bit CL4 (G, P, C[0], C[4:1], , );

    //-----------------------------------------------------------------
    // 结果和标志位生成
    //-----------------------------------------------------------------
    assign D = G ^ P ^ ((~ol) ? C[3:0] : 4'b0000);
    assign cf = (C[4] ^ so) & (~ol);
    assign zf = !D;
    assign sf = G[3] ^ P[3] ^ C[4];
    assign of = (C[4] ^ C[3]) & (~ol);

endmodule
