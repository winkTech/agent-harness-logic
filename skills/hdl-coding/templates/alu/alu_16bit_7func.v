//-----------------------------------------------------------------
//                    16位7功能算术逻辑部件
//-----------------------------------------------------------------
// 功能描述: 实现16位7功能ALU
// 应用场景: 通用算术逻辑运算
// 功能列表:
//   000: A + B
//   001: A - B
//   010: A + B + Ci
//   011: A - B - Ci
//   100: A & B
//   101: A | B
//   110: A ^ B
//   111: A ^ B
//-----------------------------------------------------------------
// 输入:
//   A       - 操作数A（16位）
//   B       - 操作数B（16位）
//   Ci      - 进位输入
//   Fc      - 功能控制（3位）
// 输出:
//   D       - 结果输出（16位）
//   cf      - 进位标志
//   zf      - 零标志
//   sf      - 符号标志
//   of      - 溢出标志
//-----------------------------------------------------------------

module alu_16bit_7func (
    input  wire [15:0] A,
    input  wire [15:0] B,
    input  wire        Ci,
    input  wire [2:0]  Fc,
    output wire [15:0] D,
    output wire        cf,
    output wire        zf,
    output wire        sf,
    output wire        of
);

    //-----------------------------------------------------------------
    // 内部信号定义
    //-----------------------------------------------------------------
    reg [15:0] G, P;
    wire [16:0] C;
    wire [3:0] Gl, Pl;
    wire [4:1] Cx;
    wire [16:1] Ct;

    //-----------------------------------------------------------------
    // 进位生成函数G
    //-----------------------------------------------------------------
    always @(*) begin
        case (Fc)
            3'b000: G = A & B;
            3'b001: G = A & (~B);
            3'b010: G = A & B;
            3'b011: G = A & (~B);
            3'b100: G = A & B;
            3'b101: G = {16{1'b0}};
            3'b110: G = A & B;
            3'b111: G = A & B;
            default: G = A & B;
        endcase
    end

    //-----------------------------------------------------------------
    // 进位传输函数P
    //-----------------------------------------------------------------
    always @(*) begin
        case (Fc)
            3'b000: P = A | B;
            3'b001: P = A | (~B);
            3'b010: P = A | B;
            3'b011: P = A | (~B);
            3'b100: P = {16{1'b0}};
            3'b101: P = A | B;
            3'b110: P = A | B;
            3'b111: P = A | B;
            default: P = A | B;
        endcase
    end

    //-----------------------------------------------------------------
    // 进位链输入
    //-----------------------------------------------------------------
    wire Cp;
    assign Cp = ((Ci & Fc[1]) ^ Fc[0]);

    //-----------------------------------------------------------------
    // 4位超前进位链实例化
    //-----------------------------------------------------------------
    carry_lookahead_4bit CL0 (G[3:0],   P[3:0],   Cp,  Ct[4:1],   Gl[0], Pl[0]);
    carry_lookahead_4bit CL1 (G[7:4],   P[7:4],   Cx[1], Ct[8:5],   Gl[1], Pl[1]);
    carry_lookahead_4bit CL2 (G[11:8],  P[11:8],  Cx[2], Ct[12:9],  Gl[2], Pl[2]);
    carry_lookahead_4bit CL3 (G[15:12], P[15:12], Cx[3], Ct[16:13], Gl[3], Pl[3]);
    carry_lookahead_4bit CLX (Gl[3:0],  Pl[3:0],  Cp,   Cx[4:1],   , );

    //-----------------------------------------------------------------
    // 进位输出拼接
    //-----------------------------------------------------------------
    assign C = {Cx[4], Ct[15:13], Cx[3], Ct[11:9], Cx[2], Ct[7:5], Cx[1], Ct[3:1], Cp};

    //-----------------------------------------------------------------
    // 结果和标志位生成
    //-----------------------------------------------------------------
    assign D = G ^ P ^ ((~Fc[2]) ? C[15:0] : {16{1'b0}});
    assign cf = (C[16] ^ Fc[0]) & (~Fc[2]);
    assign zf = !D;
    assign sf = G[15] ^ P[15] ^ ((~Fc[2]) & C[16]);
    assign of = (C[15] ^ C[16]) & (~Fc[2]);

endmodule
